const REASON_BN: [RegExp, string][] = [
  [/^Soil moisture high \((.+) m3\/m3\)/, 'মাটির আর্দ্রতা বেশি ($1 m³/m³)'],
  [/^Soil getting wetter fast \((.+)\)/, 'মাটি দ্রুত ভিজে যাচ্ছে ($1)'],
  [/^Ground movement detected \(peak (.+) g\)/, 'মাটির নড়াচড়া শনাক্ত (সর্বোচ্চ $1 g)'],
  [/^NISAR radar shows slope creep (.+) mm\/month/, 'NISAR রাডারে ঢালের ধীর সরণ $1 মিমি/মাস'],
  [/^NISAR soil moisture confirms wet ground \((.+)\)/, 'NISAR উপগ্রহ ভেজা মাটি নিশ্চিত করেছে ($1)'],
  [/^Steep slope \((.+) deg\)/, 'খাড়া ঢাল ($1°)'],
  [/^Warning: sensor and NISAR soil moisture disagree.*/, 'সেন্সর ও NISAR-এর আর্দ্রতা মিলছে না — সেন্সর পরীক্ষা প্রয়োজন'],
];
const REASON_EN: [RegExp, string][] = [
  [/m3\/m3/, 'm³/m³'],
  [/\((\d+) deg\)/, '($1°)'],
];
export function translateReason(lang: Lang, r: string): string {
  const table = lang === 'bn' ? REASON_BN : REASON_EN;
  for (const [re, rep] of table) if (re.test(r)) return r.replace(re, rep);
  return r;
}

