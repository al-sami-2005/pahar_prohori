const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
/** Convert ASCII digits to Bangla digits when the UI language is Bangla. */
export function digits(lang: Lang, v: string | number): string {
  const s = String(v);
  return lang === 'bn' ? s.replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]) : s;
}

